#!/usr/bin/env bash
set -e

# Lock both cameras to fixed exposure, gain and white balance matching what auto mode picks
# under the current lighting, and save them to scripts/config/camera_settings.sh.
# Every script applies that file before opening the cameras (configure_cameras), so commit it:
# both laptops then capture identical-looking images.
#
# Usage: scripts/tools/tune_cameras.sh
# Re-run whenever the lighting or camera position changes. Close other camera users first.

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
cd "$PROJECT_ROOT"

source "$PROJECT_ROOT/scripts/config/hardware.sh"
require_venv
require_devices FRONT_CAMERA WRIST_CAMERA
CAMERA_SETTINGS_FILE="$PROJECT_ROOT/scripts/config/camera_settings.sh"

# Only the fps/mains fixes, so tuning starts from auto mode instead of the old locked values.
rm -f "$CAMERA_SETTINGS_FILE"
configure_cameras

echo "=== Front camera (800x600 capture) ==="
FRONT=$(python "$SCRIPT_DIR/tune_cameras.py" "$FRONT_CAMERA" 800 600 2> >(filter_jpeg_warnings))
# Wrist camera quirks:
# - it reports gain 0 in auto mode, far too dark in manual; 64 is its brightest usable step
#   (64 and 128 look the same, 255 is darker)
# - its white balance is unreliable: auto sometimes settles on extreme colours, and manual
#   blue/red is not monotonic and peaks at 3000 K, the most neutral value it reaches
echo "=== Wrist camera (640x360 capture) ==="
WRIST=$(python "$SCRIPT_DIR/tune_cameras.py" "$WRIST_CAMERA" 640 360 --gain 64 --wb-temp 3000 \
    2> >(filter_jpeg_warnings))

cat > "$CAMERA_SETTINGS_FILE" <<EOF
# Generated by scripts/tools/tune_cameras.sh on $(date +%Y-%m-%d) ($(hostname)). Re-run it when the
# lighting or camera position changes. Applied by configure_cameras in hardware.sh.
FRONT_CAMERA_CONTROLS="$FRONT"
WRIST_CAMERA_CONTROLS="$WRIST"
EOF
configure_cameras
echo
cat "$CAMERA_SETTINGS_FILE"
echo "Saved. Commit scripts/config/camera_settings.sh so both laptops use the same settings."
